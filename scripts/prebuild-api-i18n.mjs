/**
 * Prebuild script: generates api/_lib/translations-data.ts
 * by reading the source translation TS files and extracting the pairs.
 *
 * Run: node scripts/prebuild-api-i18n.mjs
 */
import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const translationsDir = join(root, 'src', 'shared', 'i18n', 'config', 'translations');

const files = ['global.ts', 'projectBrowser.ts', 'controlPanel.ts', 'dashboard.ts'];

// Extract all { fr: '...', en: '...' } pairs from each file
const allPairs = [];

for (const file of files) {
  const content = readFileSync(join(translationsDir, file), 'utf-8');
  // Match each { fr: '...' | "...", en: '...' | "..." } object in the array
  const pairRegex = /\{\s*fr:\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")\s*,\s*en:\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")\s*\}/gs;
  let match;
  while ((match = pairRegex.exec(content)) !== null) {
    const fr = match[1] ?? match[2];
    const en = match[3] ?? match[4];
    if (fr != null && en != null) {
      allPairs.push({ fr, en });
    }
  }
}

console.log(`[prebuild-api-i18n] Extracted ${allPairs.length} translation pairs`);

// Generate the output TS file
const output = `// AUTO-GENERATED by scripts/prebuild-api-i18n.mjs — do not edit manually
export const APP_TRANSLATION_PAIRS: ReadonlyArray<{ fr: string; en: string }> = ${JSON.stringify(allPairs, null, 2)};
`;

const outPath = join(root, 'api', '_lib', 'translations-data.ts');
writeFileSync(outPath, output, 'utf-8');
console.log(`[prebuild-api-i18n] Wrote ${outPath}`);
