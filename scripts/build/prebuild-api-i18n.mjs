/**
 * Script de pré-build : produit api/_lib/translations-data.ts en lisant les
 * fichiers TS de traduction source et en extrayant les paires.
 *
 * Lancement : node scripts/build/prebuild-api-i18n.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..', '..');
const translationsDir = join(root, 'src', 'shared', 'i18n', 'config', 'translations');

// Chaque fichier de paires du dossier translations (index.ts ne fait que réexporter) :
// l'API traduit aussi les textes de l'éditeur. Une clé n'a jamais deux traductions
// (npm run i18n:check), donc l'ordre des fichiers ne change pas le résultat.
const LEADING_FILES = ['global.ts', 'projectBrowser.ts', 'controlPanel.ts', 'dashboard.ts'];
const files = [
  ...LEADING_FILES,
  ...readdirSync(translationsDir)
    .filter((name) => name.endsWith('.ts') && name !== 'index.ts' && !LEADING_FILES.includes(name))
    .sort(),
];

/** Décode les échappements du corps d'un littéral de chaîne TS entre guillemets (\', \", \\, \n, \u…). */
function unescapeLiteral(body) {
  return body.replace(/\\(u\{[0-9a-fA-F]+\}|u[0-9a-fA-F]{4}|x[0-9a-fA-F]{2}|.)/g, (_, esc) => {
    if (esc[0] === 'u') return String.fromCodePoint(parseInt(esc.replace(/[u{}]/g, ''), 16));
    if (esc[0] === 'x') return String.fromCharCode(parseInt(esc.slice(1), 16));
    return { n: '\n', t: '\t', r: '\r', 0: '\0' }[esc] ?? esc;
  });
}

// Extrait toutes les paires { fr: '...', en: '...' } de chaque fichier
const allPairs = [];

for (const file of files) {
  const content = readFileSync(join(translationsDir, file), 'utf-8');
  // Trouve chaque objet { fr: '...' | "...", en: '...' | "..." } du tableau
  const pairRegex = /\{\s*fr:\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")\s*,\s*en:\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")\s*,?\s*\}/gs;
  let match;
  while ((match = pairRegex.exec(content)) !== null) {
    const frRaw = match[1] ?? match[2];
    const enRaw = match[3] ?? match[4];
    const fr = frRaw == null ? null : unescapeLiteral(frRaw);
    const en = enRaw == null ? null : unescapeLiteral(enRaw);
    if (fr != null && en != null) {
      allPairs.push({ fr, en });
    }
  }
}

console.log(`[prebuild-api-i18n] Extracted ${allPairs.length} translation pairs`);

// Produit le fichier TS de sortie
const output = `// AUTO-GENERATED by scripts/build/prebuild-api-i18n.mjs — do not edit manually
export const APP_TRANSLATION_PAIRS: ReadonlyArray<{ fr: string; en: string }> = ${JSON.stringify(allPairs, null, 2)};
`;

const outPath = join(root, 'api', '_lib', 'translations-data.ts');
writeFileSync(outPath, output, 'utf-8');
console.log(`[prebuild-api-i18n] Wrote ${outPath}`);
